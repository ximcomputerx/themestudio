import type { ThemeDocument } from '../core/types'

export function exportReadme(theme: ThemeDocument): string {
  return `# ${theme.meta.name}

Theme package generated by Theme Studio.

Schema version: ${theme.schemaVersion}
Theme version: ${theme.meta.version}
Preset: ${theme.meta.presetId ?? 'custom'}

## Files

- \`theme.json\` is the full editable theme document.
- \`variables.css\` defines every color, glass, glow, border, shadow, type, and motion token on \`:root\`.
- \`components.css\` provides glass panel, button, input, dialog, neon border, and a solid terminal.
- \`tailwind.css\` is a Tailwind CSS v4 theme with inlined \`@theme\` values and two utilities.
- \`shadcn.css\` maps the theme onto shadcn/ui names and keeps the glass and neon extensions.

## Use in a React app

1. Copy this folder into the project, for example \`src/themes/${theme.meta.presetId ?? 'custom'}/\`.
2. Import the styles once from the application entry:

\`\`\`tsx
import './themes/${theme.meta.presetId ?? 'custom'}/variables.css'
import './themes/${theme.meta.presetId ?? 'custom'}/components.css'
\`\`\`

3. Use the component classes:

\`\`\`tsx
<section className="tg-panel">
  <button className="tg-button" type="button">Continue</button>
  <input className="tg-input" placeholder="Search" />
</section>
\`\`\`

4. For Tailwind CSS v4, import \`tailwind.css\` instead of \`variables.css\`. It already includes \`@import "tailwindcss"\` and the \`@theme\` block.
5. For shadcn/ui, merge the declarations in \`shadcn.css\` into the global \`:root\`. Keep \`--glass-blur\`, \`--glass-surface\`, and \`--neon-glow\` if the app renders glass or neon.

## Terminal and dense text

Do not put \`backdrop-filter\` on terminal or code surfaces. Use \`tg-terminal\`, which keeps an opaque background and the monospace stack.

## Notes

Glass opacity, blur, saturation, and contrast are already baked into the CSS variables. Changing \`theme.json\` in Theme Studio and exporting again regenerates every file from the same tokens.
`
}
